def utc_now() -> str:
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def get_connection() -> sqlite3.Connection:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(DB_PATH, timeout=10)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys = ON")
    return connection


@contextmanager
def managed_connection() -> Iterator[sqlite3.Connection]:
    conn = get_connection()
    try:
        yield conn
        conn.commit()
    except Exception:
        conn.rollback()
        raise
    finally:
        conn.close()


def _write_invoice_pdf(invoice: dict[str, Any]) -> None:
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    path = PDF_DIR / f"{invoice['id']}.pdf"
    if path.exists():
        return

    pdf = canvas.Canvas(str(path), pagesize=letter)
    pdf.setTitle(f"Invoice {invoice['invoice_number']}")
    pdf.setFont("Helvetica-Bold", 18)
    pdf.drawString(72, 730, "INVOICE")
    pdf.setFont("Helvetica", 11)
    lines = [
        f"Vendor: {invoice['vendor']}",
        f"Invoice Number: {invoice['invoice_number']}",
        f"Issue Date: {invoice['issue_date']}",
        f"Due Date: {invoice['due_date']}",
        f"Amount Due: {invoice['currency']} {Decimal(invoice['amount']):,.2f}",
        "Payment terms: Net 30",
        "This is synthetic training data generated by TaskPilot.",
    ]
    y = 680
    for line in lines:
        pdf.drawString(72, y, line)
        y -= 28
    pdf.save()


def init_db() -> None:
    DATA_DIR.mkdir(parents=True, exist_ok=True)
    PDF_DIR.mkdir(parents=True, exist_ok=True)
    with managed_connection() as connection:
        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS inbox_invoices (
                id TEXT PRIMARY KEY,
                vendor TEXT NOT NULL,
                invoice_number TEXT NOT NULL,
                issue_date TEXT NOT NULL,
                due_date TEXT NOT NULL,
                amount TEXT NOT NULL,
                currency TEXT NOT NULL,
                pdf_filename TEXT NOT NULL
            );
            CREATE TABLE IF NOT EXISTS finance_invoices (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                vendor TEXT NOT NULL,
                invoice_number TEXT NOT NULL,
                issue_date TEXT NOT NULL,
                due_date TEXT NOT NULL,
                amount TEXT NOT NULL,
                currency TEXT NOT NULL,
                source_invoice_id TEXT NOT NULL,
                created_at TEXT NOT NULL,
                UNIQUE(vendor, invoice_number)
            );
            CREATE TABLE IF NOT EXISTS tasks (
                id TEXT PRIMARY KEY,
                request TEXT NOT NULL,
                status TEXT NOT NULL,
                created_at TEXT NOT NULL,
                updated_at TEXT NOT NULL,
                result_json TEXT,
                approval_json TEXT
            );
            CREATE TABLE IF NOT EXISTS task_events (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                task_id TEXT NOT NULL REFERENCES tasks(id),
                kind TEXT NOT NULL,
                message TEXT NOT NULL,
                data_json TEXT,
                created_at TEXT NOT NULL
            );
            CREATE INDEX IF NOT EXISTS idx_task_events_task_id ON task_events(task_id, id);
            CREATE INDEX IF NOT EXISTS idx_inbox_vendor_date ON inbox_invoices(vendor, issue_date);
            """
        )
        # Safe in-place migration for databases created before the approval workflow.
        task_columns = {
            row["name"] for row in connection.execute("PRAGMA table_info(tasks)").fetchall()
        }
        if "approval_json" not in task_columns:
            connection.execute("ALTER TABLE tasks ADD COLUMN approval_json TEXT")

        for invoice in SEED_INVOICES:
            _write_invoice_pdf(invoice)
            connection.execute(
                """INSERT OR IGNORE INTO inbox_invoices
                   (id, vendor, invoice_number, issue_date, due_date, amount, currency, pdf_filename)
                   VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
                (
                    invoice["id"],
                    invoice["vendor"],
                    invoice["invoice_number"],
                    invoice["issue_date"],
                    invoice["due_date"],
                    invoice["amount"],
                    invoice["currency"],
                    f"{invoice['id']}.pdf",
                ),
            )


def row_to_dict(row: sqlite3.Row | None) -> dict[str, Any] | None:
    return dict(row) if row is not None else None


def list_inbox_invoices(query: str = "") -> list[dict[str, Any]]:
    with managed_connection() as connection:
        if query.strip():
            needle = f"%{query.strip()}%"
            rows = connection.execute(
                """SELECT * FROM inbox_invoices
                   WHERE vendor LIKE ? OR invoice_number LIKE ?
                   ORDER BY issue_date DESC, invoice_number DESC""",
                (needle, needle),
            ).fetchall()
        else:
            rows = connection.execute(
                "SELECT * FROM inbox_invoices ORDER BY issue_date DESC, invoice_number DESC"
            ).fetchall()
    return [dict(row) for row in rows]


def get_inbox_invoice(invoice_id: str) -> dict[str, Any] | None:
    with managed_connection() as connection:
        row = connection.execute("SELECT * FROM inbox_invoices WHERE id = ?", (invoice_id,)).fetchone()
    return row_to_dict(row)


def create_task(request: str) -> str:
    task_id = str(uuid.uuid4())
    now = utc_now()
    with managed_connection() as connection:
        connection.execute(
            "INSERT INTO tasks (id, request, status, created_at, updated_at) VALUES (?, ?, 'queued', ?, ?)",
            (task_id, request, now, now),
        )
    add_event(task_id, "task_created", "Task accepted", {"status": "queued"})
    return task_id


def set_task_status(task_id: str, status: str, result: dict[str, Any] | None = None) -> None:
    with managed_connection() as connection:
        connection.execute(
            "UPDATE tasks SET status = ?, updated_at = ?, result_json = ? WHERE id = ?",
            (status, utc_now(), json.dumps(result, default=str) if result is not None else None, task_id),
        )


def record_task_approval(
    task_id: str,
    approval: dict[str, Any],
    *,
    new_status: str,
    result: dict[str, Any] | None,
) -> bool:
    """Atomically resolve a pending approval exactly once.

    Returns False when another request already resolved it or the task is no
    longer waiting for approval.
    """
    serialized_approval = json.dumps(approval, default=str)
    serialized_result = json.dumps(result, default=str) if result is not None else None
    with managed_connection() as connection:
        cursor = connection.execute(
            """UPDATE tasks
               SET approval_json = ?, status = ?, updated_at = ?, result_json = ?
               WHERE id = ? AND status = 'pending_approval'""",
            (serialized_approval, new_status, utc_now(), serialized_result, task_id),
        )
        return cursor.rowcount == 1


def add_event(task_id: str, kind: str, message: str, data: dict[str, Any] | None = None) -> None:
    with managed_connection() as connection:
        connection.execute(
            "INSERT INTO task_events (task_id, kind, message, data_json, created_at) VALUES (?, ?, ?, ?, ?)",
            (task_id, kind, message, json.dumps(data, default=str) if data is not None else None, utc_now()),
        )


def get_task(task_id: str) -> dict[str, Any] | None:
    with managed_connection() as connection:
        row = connection.execute("SELECT * FROM tasks WHERE id = ?", (task_id,)).fetchone()
        if row is None:
            return None
        task = dict(row)
        event_rows = connection.execute(
            "SELECT kind, message, data_json, created_at FROM task_events WHERE task_id = ? ORDER BY id",
            (task_id,),
        ).fetchall()
    raw_result = task.pop("result_json")
    raw_approval = task.pop("approval_json", None)
    task["result"] = json.loads(raw_result) if raw_result else None
    task["approval"] = json.loads(raw_approval) if raw_approval else None
    task["events"] = []
    for event in event_rows:
        item = dict(event)
        raw_data = item.pop("data_json")
        item["data"] = json.loads(raw_data) if raw_data else None
        task["events"].append(item)
    return task


def list_tasks(limit: int = 30) -> list[dict[str, Any]]:
    with managed_connection() as connection:
        rows = connection.execute(
            "SELECT id, request, status, created_at, updated_at FROM tasks ORDER BY created_at DESC LIMIT ?",
            (limit,),
        ).fetchall()
    return [dict(row) for row in rows]


def insert_finance_invoice(invoice: InvoiceData, source_invoice_id: str) -> None:
    with managed_connection() as connection:
        connection.execute(
            """INSERT INTO finance_invoices
               (vendor, invoice_number, issue_date, due_date, amount, currency, source_invoice_id, created_at)
               VALUES (?, ?, ?, ?, ?, ?, ?, ?)""",
            (
                invoice.vendor,
                invoice.invoice_number,
                invoice.issue_date,
                invoice.due_date,
                str(invoice.amount.quantize(Decimal("0.01"))),
                invoice.currency,
                source_invoice_id,
                utc_now(),
            ),
        )


def get_finance_invoice(vendor: str, invoice_number: str) -> dict[str, Any] | None:
    with managed_connection() as connection:
        row = connection.execute(
            "SELECT * FROM finance_invoices WHERE lower(vendor) = lower(?) AND invoice_number = ?",
            (vendor, invoice_number),
        ).fetchone()
    return row_to_dict(row)


def list_finance_invoices() -> list[dict[str, Any]]:
    with managed_connection() as connection:
        rows = connection.execute("SELECT * FROM finance_invoices ORDER BY id DESC").fetchall()
    return [dict(row) for row in rows]
